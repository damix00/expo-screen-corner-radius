#!/usr/bin/env node
// Regenerates ios/CornerRadiusData.swift from BezelKit's device data.
//
//   node scripts/sync-bezelkit.mjs          # rewrite the file
//   node scripts/sync-bezelkit.mjs --check  # exit 1 if the file is out of date
//   node scripts/sync-bezelkit.mjs --source path/to/bezel.min.json

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const SOURCE_URL =
    "https://raw.githubusercontent.com/markbattistella/BezelKit/main/Sources/BezelKit/Resources/bezel.min.json";
const OUTPUT = join(
    dirname(fileURLToPath(import.meta.url)),
    "..",
    "ios",
    "CornerRadiusData.swift"
);

const args = process.argv.slice(2);
const check = args.includes("--check");
const sourceIndex = args.indexOf("--source");
const sourcePath = sourceIndex === -1 ? null : args[sourceIndex + 1];

async function loadDevices() {
    if (sourcePath) {
        return JSON.parse(readFileSync(sourcePath, "utf8")).devices;
    }
    const response = await fetch(SOURCE_URL);
    if (!response.ok) {
        throw new Error(`Fetching ${SOURCE_URL} failed: ${response.status}`);
    }
    return (await response.json()).devices;
}

// Sorts "iPhone10,3" after "iPhone9,4" by comparing the numbers, not the text.
function compareIdentifiers(a, b) {
    const parse = (id) => id.match(/\d+/g).map(Number);
    const [a1, a2] = parse(a);
    const [b1, b2] = parse(b);
    return a1 - b1 || a2 - b2;
}

function table(name, devices) {
    const rows = Object.keys(devices)
        .sort(compareIdentifiers)
        .map((id) => `    "${id}": ${devices[id].bezel}`);
    return `let ${name}: CornerData = [\n${rows.join(",\n")}\n]`;
}

function corners({ topLeft, topRight, bottomLeft, bottomRight }) {
    if (topLeft === topRight && topLeft === bottomLeft && topLeft === bottomRight) {
        return `CornerRadii(uniform: ${topLeft})`;
    }
    return `CornerRadii(topLeft: ${topLeft}, topRight: ${topRight}, bottomLeft: ${bottomLeft}, bottomRight: ${bottomRight})`;
}

function multiScreenTable(devices) {
    const entries = Object.entries(devices)
        .filter(([, device]) => Array.isArray(device.screens))
        .sort(([a], [b]) => compareIdentifiers(a, b))
        .map(([id, device]) => {
            const screens = device.screens.map(
                (screen) =>
                    `        // ${device.name}, ${screen.name.toLowerCase()} screen\n` +
                    `        ScreenCorners(\n` +
                    `            nativeSize: CGSize(width: ${screen.nativeSize[0]}, height: ${screen.nativeSize[1]}),\n` +
                    `            corners: ${corners(screen.corners)}\n` +
                    `        )`
            );
            return `    "${id}": [\n${screens.join(",\n")}\n    ]`;
        });
    if (entries.length === 0) {
        return "let multiScreenRadii: [String: [ScreenCorners]] = [:]";
    }
    return `let multiScreenRadii: [String: [ScreenCorners]] = [\n${entries.join(",\n")}\n]`;
}

function render(devices) {
    // iPod touch reports the phone idiom, so it shares the iPhone table.
    const phones = { ...devices.iPhone, ...(devices.iPod ?? {}) };
    const all = { ...phones, ...devices.iPad };
    return `import CoreGraphics

// Corner radii in points, keyed by hardware model identifier.
// Generated by scripts/sync-bezelkit.mjs from BezelKit: https://github.com/markbattistella/BezelKit
// Do not edit by hand. Fix the data upstream, then run \`npm run sync-data\`.

typealias CornerData = [String: Double]

${table("iphoneRadii", phones)}

${table("ipadRadii", devices.iPad)}

// Devices whose screens don't share one radius on every corner. Corners are measured with the
// device held upright, and \`nativeSize\` is \`UIScreen.nativeBounds\` in pixels, which tells the
// screens apart.
${multiScreenTable(all)}
`;
}

const output = render(await loadDevices());
const current = readFileSync(OUTPUT, "utf8");

if (check) {
    if (current !== output) {
        console.error(
            "ios/CornerRadiusData.swift is out of date with BezelKit. Run `npm run sync-data`."
        );
        process.exit(1);
    }
    console.log("ios/CornerRadiusData.swift is up to date with BezelKit.");
} else if (current === output) {
    console.log("ios/CornerRadiusData.swift is already up to date.");
} else {
    writeFileSync(OUTPUT, output);
    console.log("Updated ios/CornerRadiusData.swift.");
}
